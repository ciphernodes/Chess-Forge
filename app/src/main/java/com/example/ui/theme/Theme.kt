private val LightColorScheme = lightColorScheme(
    primary = ForgeTeal,
    onPrimary = Color.White,
    primaryContainer = Color(0xFFCCFBF1),
    onPrimaryContainer = Color(0xFF115E59),
    secondary = ForgeEmber,
    onSecondary = Color.White,
